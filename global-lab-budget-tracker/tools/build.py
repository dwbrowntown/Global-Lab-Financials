#!/usr/bin/env python3
"""Assemble the Global Lab Budget Tracker from src/ into dist/.

Usage: python3 -I tools/build.py <root> <build-label>
  <root>        the global-lab-budget-tracker folder
  <build-label> e.g. "build 2 (2026-11-13)"; shown in the page footer and the stamp

Writes dist/index.html, dist/settings.js and dist/data.js, all pure ASCII.
Non-ASCII characters are escaped by context: \\uXXXX inside <script>, CSS escapes inside <style>, HTML entities elsewhere.
"""
import os
import re
import sys


def js_escape(text):
    return ''.join(c if ord(c) < 128 else '\\u%04x' % ord(c) for c in text)


def css_escape(text):
    return ''.join(c if ord(c) < 128 else '\\%06x' % ord(c) for c in text)


def html_escape(text):
    return ''.join(c if ord(c) < 128 else '&#x%x;' % ord(c) for c in text)


def main():
    root, label = sys.argv[1], sys.argv[2]
    src = os.path.join(root, 'src')
    parts = os.path.join(src, 'parts')
    dist = os.path.join(root, 'dist')
    os.makedirs(dist, exist_ok=True)

    def read(p):
        with open(p, encoding='utf-8') as f:
            return f.read()

    css = read(os.path.join(parts, 'style.css'))
    body = read(os.path.join(parts, 'body.html'))
    app = read(os.path.join(parts, 'app.js'))
    if '{{BUILD}}' not in app:
        sys.exit('app.js has no {{BUILD}} placeholder')
    app = app.replace('{{BUILD}}', label)
    for bad in ('</script', '<!--'):
        if bad in app.lower():
            sys.exit('app.js contains %r, which would break the inline script' % bad)

    page = '\n'.join([
        '<!-- Built from global-lab-budget-tracker/src by tools/build.py, %s. Do not edit this file; change src and rebuild. -->' % label,
        '<title>Global Lab Budget Tracker</title>',
        '<link rel="preconnect" href="https://fonts.googleapis.com">',
        '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
        '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=DM+Sans:opsz,wght@9..40,400;9..40,500;9..40,600;9..40,700&family=DM+Mono:wght@400;500&display=swap">',
        '<style>', css_escape(css).rstrip(), '</style>',
        '',
        html_escape(body).rstrip(),
        '',
        '<script src="settings.js"></script>',
        '<script src="data.js"></script>',
        '<script>', js_escape(app).rstrip(), '</script>',
        '',
    ])
    page.encode('ascii')  # raises if anything slipped through
    if re.search('—', page):
        sys.exit('em dash found')

    out = {'index.html': page,
           'settings.js': js_escape(read(os.path.join(src, 'settings.js'))),
           'data.js': js_escape(read(os.path.join(src, 'data.js')))}
    for name, text in out.items():
        text.encode('ascii')
        with open(os.path.join(dist, name), 'w', encoding='ascii', newline='\n') as f:
            f.write(text)
    print('built %s: %s' % (label, ', '.join('%s %d bytes' % (n, len(t)) for n, t in out.items())))


if __name__ == '__main__':
    main()
